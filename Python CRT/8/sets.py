##union(|)
set1={1,2,3,4,5,6}
set2={4,5,6,9,7,8}
print(set1|set2)
#intersection(&)
print(set1&set2)
#difference(-)
print(set1-set2)
#symmetric difference(^)
print(set1^set2)
